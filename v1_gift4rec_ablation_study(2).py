def run_ablation_study(ablation_configs, splits, user_feats, user_item_dict,
                       cold_users, n_users, n_items, config, device, n_runs=3):
    """Run complete ablation study with multiple runs"""

    all_results = {}

    print("="*100)
    print("🔬 GIFT4Rec ABLATION STUDY")
    print("="*100)
    print(f"   Number of variants: {len(ablation_configs)}")
    print(f"   Runs per variant: {n_runs}")
    print(f"   Total experiments: {len(ablation_configs) * n_runs}")
    print("="*100 + "\n")

    for variant_key, variant_config in ablation_configs.items():
        print(f"\n{'='*80}")
        print(f"📊 Running: {variant_config['name']}")
        print(f"{'='*80}")
        print(f"   Config: {variant_config}")

        variant_results = []

        for run_id in range(n_runs):
            print(f"\n   🏃 Run {run_id + 1}/{n_runs}")
            set_seed(42 + run_id)  # Different seed for each run

            # Re-split data for each run
            splits_run, cold_users_run = split_data(ratings, user_item_dict,
                                                    config['active_ratio'],
                                                    config['cold_ratio'])

            results = train_ablation_variant(
                variant_key, variant_config,
                splits_run, user_feats, user_item_dict,
                cold_users_run, n_users, n_items, config, device,
                verbose=(run_id == 0)  # Only show progress for first run
            )

            variant_results.append(results)

            if results:
                print(f"      Overall NDCG@10: {results['overall'].get('NDCG@10', 0):.2f}%")

        # Aggregate results across runs
        all_results[variant_key] = {
            'name': variant_config['name'],
            'config': variant_config,
            'runs': variant_results,
            'aggregated': aggregate_results(variant_results)
        }

        print(f"\n   ✅ {variant_config['name']} completed!")
        if all_results[variant_key]['aggregated']:
            agg = all_results[variant_key]['aggregated']['overall']
            print(f"   📊 Mean NDCG@10: {agg['NDCG@10']['mean']:.2f}% ± {agg['NDCG@10']['std']:.2f}%")

    return all_results


def aggregate_results(runs_results):
    """Aggregate results across multiple runs"""
    if not runs_results or not runs_results[0]:
        return None

    aggregated = {}

    for split_name in runs_results[0].keys():
        aggregated[split_name] = {}

        for metric in runs_results[0][split_name].keys():
            values = [r[split_name][metric] for r in runs_results if r and split_name in r and metric in r[split_name]]
            if values:
                aggregated[split_name][metric] = {
                    'mean': np.mean(values),
                    'std': np.std(values),
                    'min': np.min(values),
                    'max': np.max(values)
                }

    return aggregated

