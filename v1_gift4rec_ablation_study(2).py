class TrainDataset(Dataset):
    def __init__(self, data, n_items, user_items, n_neg=4):
        self.data = data
        self.n_items = n_items
        self.user_items = user_items
        self.n_neg = n_neg

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        user, pos = self.data[idx]
        pos_set = set(self.user_items.get(user, []))

        neg = []
        while len(neg) < self.n_neg:
            n = random.randint(0, self.n_items - 1)
            if n not in pos_set:
                neg.append(n)

        return user, pos, neg

def collate_fn(batch):
    users = torch.LongTensor([b[0] for b in batch])
    pos = torch.LongTensor([b[1] for b in batch])
    neg = torch.LongTensor([b[2] for b in batch])
    return users, pos, neg


def evaluate(model, edge_index, user_feats, test_data, user_items, cold_users, device, k_list=[10, 20, 50]):
    if not test_data:
        return {}

    model.eval()

    users = [d[0] for d in test_data]
    items = [d[1] for d in test_data]

    batch_size = 256
    all_metrics = {f'{m}@{k}': [] for k in k_list for m in ['R', 'HR', 'NDCG']}

    for start in range(0, len(users), batch_size):
        end = min(start + batch_size, len(users))
        batch_users = users[start:end]
        batch_items = items[start:end]

        user_ids = torch.LongTensor(batch_users).to(device)
        ground_truth = torch.LongTensor(batch_items).to(device)
        is_cold = torch.BoolTensor([u in cold_users for u in batch_users]).to(device)

        with torch.no_grad():
            scores = model.predict(edge_index, user_feats, user_ids,
                                  is_cold if is_cold.any() else None)

        # Mask training items
        for i, u in enumerate(batch_users):
            if u in user_items:
                scores[i, user_items[u]] = float('-inf')

        max_k = max(k_list)
        _, topk = torch.topk(scores, max_k, dim=1)

        for k in k_list:
            for i, (top, gt) in enumerate(zip(topk[:, :k], ground_truth)):
                hit = (top == gt).any().float().item()
                all_metrics[f'R@{k}'].append(hit)
                all_metrics[f'HR@{k}'].append(hit)

                if hit:
                    rank = (top == gt).nonzero(as_tuple=True)[0][0].item()
                    all_metrics[f'NDCG@{k}'].append(1.0 / np.log2(rank + 2))
                else:
                    all_metrics[f'NDCG@{k}'].append(0.0)

    return {k: np.mean(v) * 100 for k, v in all_metrics.items()}

