def prepare_data(ratings, users):
    """Encode IDs và tạo user features"""
    all_users = sorted(ratings['user_id'].unique())
    all_items = sorted(ratings['item_id'].unique())

    u2i = {u: i for i, u in enumerate(all_users)}
    i2i = {i: idx for idx, i in enumerate(all_items)}

    ratings = ratings.copy()
    ratings['uidx'] = ratings['user_id'].map(u2i)
    ratings['iidx'] = ratings['item_id'].map(i2i)

    n_users = len(all_users)
    n_items = len(all_items)

    # User features
    users = users[users['user_id'].isin(all_users)].copy()
    users['uidx'] = users['user_id'].map(u2i)

    gender_enc = pd.get_dummies(users['gender'], prefix='g')
    age_enc = pd.get_dummies(users['age'], prefix='a')
    occ_enc = pd.get_dummies(users['occupation'], prefix='o')

    user_feat_df = pd.concat([users[['uidx']], gender_enc, age_enc, occ_enc], axis=1)
    user_feat_df = user_feat_df.sort_values('uidx')

    feat_cols = [c for c in user_feat_df.columns if c != 'uidx']
    user_feats = torch.FloatTensor(user_feat_df[feat_cols].values)

    return ratings, n_users, n_items, user_feats

