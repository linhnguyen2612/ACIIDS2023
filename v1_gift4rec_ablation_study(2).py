"""## 8. 🎯 GIFT4Rec Model with Ablation Support"""

class GIFT4RecAblation(nn.Module):
    """GIFT4Rec Model with Ablation Study Support"""

    def __init__(self, n_users, n_items, user_feat_dim,
                 embed_dim=64, n_layers=2, hidden_dim=128, dropout=0.2,
                 ablation_config=None):
        super().__init__()

        # Default ablation config (full model)
        if ablation_config is None:
            ablation_config = ABLATION_CONFIGS['full']

        self.ablation = ablation_config
        self.n_users = n_users
        self.n_items = n_items
        self.embed_dim = embed_dim
        self.dropout_rate = dropout

        # GNN Module (optional)
        if self.ablation['use_gnn']:
            self.gnn = GNNModule(n_users, n_items, embed_dim, n_layers,
                                self.ablation['use_layer_agg'])
        else:
            self.gnn = None
            # Fallback item embeddings when no GNN
            self.item_emb = nn.Embedding(n_items, embed_dim)
            nn.init.xavier_uniform_(self.item_emb.weight)

        # Side Information Encoder (optional)
        if self.ablation['use_side_info']:
            self.side_encoder = SideInfoEncoder(user_feat_dim, embed_dim)
        else:
            self.side_encoder = None

        # Weight Generator (optional)
        if self.ablation['use_weight_gen'] and self.ablation['use_gnn'] and self.ablation['use_side_info']:
            self.weight_gen = WeightGenerator(embed_dim * 2, hidden_dim)
        else:
            self.weight_gen = None

        self.register_buffer('mean_user_emb', torch.zeros(embed_dim))

    def build_graph(self, train_data):
        """Build edge index from training data"""
        edges = []
        for u, i in train_data:
            edges.append([u, self.n_users + i])
            edges.append([self.n_users + i, u])
        edge_index = torch.LongTensor(edges).t().contiguous()
        return edge_index

    def get_user_embedding(self, user_emb_gnn, side_emb, use_dropout=True):
        """Get final user embedding based on ablation config"""

        # Case 1: No side info - use only GNN embedding
        if not self.ablation['use_side_info']:
            return user_emb_gnn, torch.ones(user_emb_gnn.size(0), 1, device=user_emb_gnn.device)

        # Case 2: No GNN - use only side info embedding
        if not self.ablation['use_gnn']:
            return side_emb, torch.zeros(side_emb.size(0), 1, device=side_emb.device)

        # Case 3: Both available - fuse them
        if self.ablation['use_weight_gen']:
            # Adaptive fusion with weight generator
            concat = torch.cat([user_emb_gnn, side_emb], dim=-1)
            alpha = self.weight_gen(concat)
        else:
            # Fixed fusion (α = 0.5)
            alpha = torch.full((user_emb_gnn.size(0), 1), 0.5, device=user_emb_gnn.device)

        # Apply dropout if enabled
        if self.ablation['use_dropout'] and use_dropout and self.training:
            mask = torch.rand(alpha.size(0), 1, device=alpha.device) < self.dropout_rate
            final = torch.where(
                mask.expand_as(user_emb_gnn),
                side_emb,
                alpha * user_emb_gnn + (1 - alpha) * side_emb
            )
        else:
            final = alpha * user_emb_gnn + (1 - alpha) * side_emb

        return final, alpha

    def forward(self, edge_index, user_feats, user_ids, pos_items, neg_items):
        # Get embeddings
        if self.ablation['use_gnn']:
            user_emb, item_emb = self.gnn(edge_index)
            u_behavior = user_emb[user_ids]
        else:
            u_behavior = None
            item_emb = self.item_emb.weight

        if self.ablation['use_side_info']:
            side_emb_all = self.side_encoder(user_feats)
            u_side = side_emb_all[user_ids]
        else:
            u_side = None

        # Get final user embedding
        if u_behavior is not None and u_side is not None:
            final_u, alpha = self.get_user_embedding(u_behavior, u_side, use_dropout=True)
        elif u_behavior is not None:
            final_u, alpha = u_behavior, torch.ones(u_behavior.size(0), 1, device=u_behavior.device)
        else:
            final_u, alpha = u_side, torch.zeros(u_side.size(0), 1, device=u_side.device)

        pos_emb = item_emb[pos_items]
        neg_emb = item_emb[neg_items]

        pos_scores = (final_u * pos_emb).sum(-1)
        neg_scores = (final_u.unsqueeze(1) * neg_emb).sum(-1)

        bpr_loss = -torch.log(torch.sigmoid(pos_scores.unsqueeze(1) - neg_scores) + 1e-10).mean()

        # L2 regularization
        l2_reg = 1e-5 * (
            final_u.norm(2).pow(2) +
            pos_emb.norm(2).pow(2) +
            neg_emb.norm(2).pow(2)
        ) / user_ids.size(0)

        return {
            'loss': bpr_loss + l2_reg,
            'bpr': bpr_loss,
            'alpha': alpha.mean()
        }

    def compute_global_loss(self, edge_index, user_feats, val_users, val_items, item_emb_cache=None):
        """Global SIF loss (only if enabled)"""
        if not self.ablation['use_global_sif']:
            return torch.tensor(0.0, device=val_users.device)

        if not self.ablation['use_gnn'] or not self.ablation['use_side_info']:
            return torch.tensor(0.0, device=val_users.device)

        with torch.no_grad():
            user_emb, item_emb = self.gnn(edge_index)
            side_emb = self.side_encoder(user_feats)

        u_behavior = user_emb[val_users]
        u_side = side_emb[val_users]

        n_sample = min(1000, item_emb.size(0))
        sample_idx = torch.randperm(item_emb.size(0), device=item_emb.device)[:n_sample]
        item_sample = item_emb[sample_idx]

        final_u, alpha = self.get_user_embedding(u_behavior, u_side, use_dropout=False)

        scores = torch.mm(final_u, item_sample.t())
        targets = (sample_idx.unsqueeze(0) == val_items.unsqueeze(1)).float().to(scores.device)

        loss = F.binary_cross_entropy_with_logits(scores, targets)
        return loss

    def update_mean_embedding(self, edge_index, non_cold_ids):
        """Update mean user embedding for cold-start"""
        if not self.ablation['use_gnn']:
            return

        with torch.no_grad():
            user_emb, _ = self.gnn(edge_index)
            self.mean_user_emb = user_emb[non_cold_ids].mean(dim=0)

    def predict(self, edge_index, user_feats, user_ids, is_cold=None):
        """Predict scores for evaluation"""
        with torch.no_grad():
            if self.ablation['use_gnn']:
                user_emb, item_emb = self.gnn(edge_index)
            else:
                user_emb = None
                item_emb = self.item_emb.weight

            if self.ablation['use_side_info']:
                side_emb = self.side_encoder(user_feats)
            else:
                side_emb = None

            if user_emb is not None:
                u_behavior = user_emb[user_ids]
            else:
                u_behavior = None

            if side_emb is not None:
                u_side = side_emb[user_ids]
            else:
                u_side = None

            # Handle cold users
            if is_cold is not None and is_cold.any() and u_behavior is not None:
                u_behavior[is_cold] = self.mean_user_emb

            # Get final embedding
            if u_behavior is not None and u_side is not None:
                final_u, _ = self.get_user_embedding(u_behavior, u_side, use_dropout=False)
            elif u_behavior is not None:
                final_u = u_behavior
            else:
                final_u = u_side

            scores = torch.mm(final_u, item_emb.t())
            return scores

