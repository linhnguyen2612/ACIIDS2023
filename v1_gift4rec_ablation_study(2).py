"""## 7. 🧠 Model Components"""

class LightGCNConv(nn.Module):
    """Light Graph Convolution"""

    def __init__(self):
        super().__init__()

    def forward(self, x, edge_index, edge_weight=None):
        row, col = edge_index
        deg = torch.bincount(row, minlength=x.size(0)).float()
        deg_inv_sqrt = deg.pow(-0.5)
        deg_inv_sqrt[deg_inv_sqrt == float('inf')] = 0

        norm = deg_inv_sqrt[row] * deg_inv_sqrt[col]

        out = torch.zeros_like(x)
        out.index_add_(0, row, x[col] * norm.unsqueeze(-1))

        return out


class GNNModule(nn.Module):
    """GNN module with optional layer aggregation"""

    def __init__(self, n_users, n_items, embed_dim=64, n_layers=2, use_layer_agg=True):
        super().__init__()
        self.n_users = n_users
        self.n_items = n_items
        self.n_layers = n_layers
        self.embed_dim = embed_dim
        self.use_layer_agg = use_layer_agg

        self.user_emb = nn.Embedding(n_users, embed_dim)
        self.item_emb = nn.Embedding(n_items, embed_dim)

        self.convs = nn.ModuleList([LightGCNConv() for _ in range(n_layers)])

        nn.init.xavier_uniform_(self.user_emb.weight)
        nn.init.xavier_uniform_(self.item_emb.weight)

    def forward(self, edge_index):
        x = torch.cat([self.user_emb.weight, self.item_emb.weight], dim=0)

        if self.use_layer_agg:
            all_emb = [x]
            for conv in self.convs:
                x = conv(x, edge_index)
                all_emb.append(x)
            x = torch.stack(all_emb, dim=1).mean(dim=1)
        else:
            # Only use final layer output
            for conv in self.convs:
                x = conv(x, edge_index)

        return x[:self.n_users], x[self.n_users:]


class WeightGenerator(nn.Module):
    """Adaptive weight generator for embedding fusion"""

    def __init__(self, input_dim, hidden_dim=128):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.LayerNorm(hidden_dim),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(hidden_dim, hidden_dim // 2),
            nn.ReLU(),
            nn.Linear(hidden_dim // 2, 1),
            nn.Sigmoid()
        )

    def forward(self, x):
        return self.net(x)


class SideInfoEncoder(nn.Module):
    """Encode user side information"""

    def __init__(self, input_dim, embed_dim):
        super().__init__()
        self.encoder = nn.Sequential(
            nn.Linear(input_dim, embed_dim * 2),
            nn.LayerNorm(embed_dim * 2),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(embed_dim * 2, embed_dim),
            nn.LayerNorm(embed_dim)
        )

    def forward(self, x):
        return self.encoder(x)

