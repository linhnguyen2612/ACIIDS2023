def prepare_data(ratings, users):
    """Encode IDs và tạo user features"""
    # Lấy unique users và items từ ratings
    all_users = sorted(ratings['user_id'].unique())
    all_items = sorted(ratings['item_id'].unique())

    # Tạo mapping liên tục từ 0
    u2i = {u: i for i, u in enumerate(all_users)}
    i2i = {i: idx for idx, i in enumerate(all_items)}

    ratings = ratings.copy()
    ratings['uidx'] = ratings['user_id'].map(u2i)
    ratings['iidx'] = ratings['item_id'].map(i2i)

    n_users = len(all_users)
    n_items = len(all_items)

    # User features
    users_filtered = users[users['user_id'].isin(all_users)].copy()
    users_filtered = users_filtered.set_index('user_id').loc[all_users].reset_index()

    users_filtered['g'] = users_filtered['gender'].map({'M': 0, 'F': 1})
    users_filtered['a'] = LabelEncoder().fit_transform(users_filtered['age'])
    users_filtered['o'] = LabelEncoder().fit_transform(users_filtered['occupation'])

    ng, na, no = 2, users_filtered['a'].nunique(), users_filtered['o'].nunique()
    feats = np.zeros((n_users, ng + na + no), dtype=np.float32)

    for i, (_, r) in enumerate(users_filtered.iterrows()):
        feats[i, r['g']] = 1
        feats[i, ng + r['a']] = 1
        feats[i, ng + na + r['o']] = 1

    return ratings, n_users, n_items, torch.FloatTensor(feats), u2i, i2i

