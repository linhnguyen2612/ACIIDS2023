"""## 10. 🚀 Training"""

def train_gift4rec(model, splits, user_feats, user_item_dict, cold_users, config, device):
    model = model.to(device)
    user_feats = user_feats.to(device)

    # Build graph
    edge_index = model.build_graph(splits['train']).to(device)
    print(f"   Edge index shape: {edge_index.shape}")
    print(f"   Edge index range: {edge_index.min().item()} - {edge_index.max().item()}")
    print(f"   Expected max: {model.n_users + model.n_items - 1}")

    # Dataset
    dataset = TrainDataset(splits['train'], model.n_items, user_item_dict, config['neg_samples'])
    loader = DataLoader(dataset, config['batch_size'], shuffle=True,
                       collate_fn=collate_fn, num_workers=0, pin_memory=True)

    # Optimizers
    optimizer = torch.optim.AdamW(model.parameters(), lr=config['lr'], weight_decay=config['weight_decay'])
    global_optimizer = torch.optim.Adam(model.weight_gen.parameters(), lr=config['lr'] * 0.1)
    scheduler = torch.optim.lr_scheduler.StepLR(optimizer, step_size=20, gamma=0.95)

    non_cold_ids = torch.LongTensor([u for u in range(model.n_users) if u not in cold_users]).to(device)

    best_score = 0
    best_state = None

    print("\n" + "="*90)
    print("🚀 Training GIFT4Rec")
    print("="*90)

    for epoch in range(1, config['epochs'] + 1):
        model.train()
        total_loss, total_bpr, total_alpha = 0, 0, 0

        pbar = tqdm(loader, desc=f"Epoch {epoch}/{config['epochs']}", leave=False)
        for users, pos, neg in pbar:
            users = users.to(device)
            pos = pos.to(device)
            neg = neg.to(device)

            optimizer.zero_grad()
            outputs = model(edge_index, user_feats, users, pos, neg)
            outputs['loss'].backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()

            total_loss += outputs['loss'].item()
            total_bpr += outputs['bpr'].item()
            total_alpha += outputs['alpha'].item()

            pbar.set_postfix({'loss': f"{outputs['loss'].item():.4f}"})

        # Global SIF
        if epoch % 3 == 0 and splits['val']:
            model.train()
            val_users = torch.LongTensor([v[0] for v in splits['val'][:500]]).to(device)
            val_items = torch.LongTensor([v[1] for v in splits['val'][:500]]).to(device)

            global_optimizer.zero_grad()
            global_loss = model.compute_global_loss(edge_index, user_feats, val_users, val_items)
            global_loss.backward()
            global_optimizer.step()

        scheduler.step()

        # Clear cache
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

        # Evaluate
        if epoch % config['eval_freq'] == 0 or epoch == 1:
            model.update_mean_embedding(edge_index, non_cold_ids)

            results = {}
            for name, data in [('active', splits['test_active']),
                              ('warm', splits['test_warm']),
                              ('cold', splits['test_cold'])]:
                if data:
                    results[name] = evaluate(model, edge_index, user_feats,
                                            data, user_item_dict, cold_users, device)

            if results:
                overall = {}
                for m in ['R@10','R@20','R@50','HR@10','HR@20','HR@50','NDCG@10','NDCG@20','NDCG@50']:
                    vals = [results[s][m] for s in results if m in results.get(s, {})]
                    if vals:
                        overall[m] = np.mean(vals)
                results['overall'] = overall

            n_batch = len(loader)
            print(f"\n📊 Epoch {epoch}/{config['epochs']}")
            print(f"   Loss: {total_loss/n_batch:.4f} | BPR: {total_bpr/n_batch:.4f} | Alpha: {total_alpha/n_batch:.4f}")

            print(f"\n   {'Set':<10} | {'R@10':>6} {'R@20':>6} {'R@50':>6} | "
                  f"{'HR@10':>6} {'HR@20':>6} {'HR@50':>6} | "
                  f"{'NDCG@10':>7} {'NDCG@20':>7} {'NDCG@50':>7}")
            print("   " + "-"*85)

            for name in ['active', 'warm', 'cold', 'overall']:
                if name in results:
                    r = results[name]
                    marker = "⭐" if name == 'overall' else "  "
                    print(f" {marker} {name.upper():<8} | {r['R@10']:>6.2f} {r['R@20']:>6.2f} {r['R@50']:>6.2f} | "
                          f"{r['HR@10']:>6.2f} {r['HR@20']:>6.2f} {r['HR@50']:>6.2f} | "
                          f"{r['NDCG@10']:>7.2f} {r['NDCG@20']:>7.2f} {r['NDCG@50']:>7.2f}")

            if 'overall' in results and results['overall'].get('R@50', 0) > best_score:
                best_score = results['overall']['R@50']
                best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
                print(f"   ✅ New best! (R@50: {best_score:.2f})")

    if best_state:
        model.load_state_dict(best_state)
        model = model.to(device)

    return model, edge_index

