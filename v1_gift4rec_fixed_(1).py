def split_users(ratings, active_ratio=0.8, cold_ratio=0.1):
    counts = ratings.groupby('uidx').size().sort_values(ascending=False)
    n = len(counts)

    active = set(counts.iloc[:int(n*active_ratio)].index)
    cold = set(counts.iloc[-int(n*cold_ratio):].index)
    warm = set(counts.index) - active - cold

    return active, warm, cold

def create_splits(ratings, active, warm, cold):
    train, val, test_active, test_warm, test_cold = [], [], [], [], []

    for uid, g in ratings.groupby('uidx'):
        items = g['iidx'].tolist()

        if uid in active:
            if len(items) >= 3:
                train.extend([(uid, i) for i in items[:-2]])
                val.append((uid, items[-2]))
                test_active.append((uid, items[-1]))
            elif len(items) == 2:
                train.append((uid, items[0]))
                test_active.append((uid, items[1]))
            else:
                train.append((uid, items[0]))

        elif uid in warm:
            if len(items) >= 2:
                train.extend([(uid, i) for i in items[:-1]])
                test_warm.append((uid, items[-1]))
            else:
                train.append((uid, items[0]))

        else:  # cold
            if items:
                test_cold.append((uid, items[0]))

    return {
        'train': train, 'val': val,
        'test_active': test_active,
        'test_warm': test_warm,
        'test_cold': test_cold
    }

