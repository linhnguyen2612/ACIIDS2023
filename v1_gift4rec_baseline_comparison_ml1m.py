class KGATConv(nn.Module):
    def __init__(s,ind,outd,nh=4,dr=0.1):
        super().__init__()
        s.nh,s.hd=nh,outd//nh
        s.W=nn.Linear(ind,outd,bias=False)
        s.a=nn.Parameter(torch.randn(nh,s.hd*2))
        s.dr=nn.Dropout(dr)
        s.lr=nn.LeakyReLU(0.2)
        nn.init.xavier_uniform_(s.W.weight);nn.init.xavier_uniform_(s.a)

    def forward(s,x,e):
        h=s.W(x).view(x.size(0),s.nh,s.hd)
        r,c=e
        hi,hj=h[r],h[c]
        att=(torch.cat([hi,hj],-1)*s.a.unsqueeze(0)).sum(-1)
        att=s.lr(att)
        em=torch.zeros(x.size(0),s.nh,device=x.device)
        em.index_reduce_(0,r,att,'amax',include_self=False)
        att=torch.exp(att-em[r])
        es=torch.zeros(x.size(0),s.nh,device=x.device)
        es.index_add_(0,r,att)
        att=s.dr(att/(es[r]+1e-10))
        out=torch.zeros(x.size(0),s.nh,s.hd,device=x.device)
        out.index_add_(0,r,hj*att.unsqueeze(-1))
        return out.view(x.size(0),-1)

class KGAT(nn.Module):
    def __init__(s,nu,ni,ifd,ed=64,nl=2,nh=4,dr=0.1):
        super().__init__()
        s.n_users,s.n_items=nu,ni
        s.ue,s.ie=nn.Embedding(nu,ed),nn.Embedding(ni,ed)
        s.ienc=nn.Linear(ifd,ed)
        s.convs=nn.ModuleList([KGATConv(ed,ed,nh,dr) for _ in range(nl)])
        nn.init.xavier_uniform_(s.ue.weight);nn.init.xavier_uniform_(s.ie.weight)

    def forward(s,e,itf,ui,pi,ni):
        ii=s.ie.weight+s.ienc(itf)
        x=torch.cat([s.ue.weight,ii],0)
        all_e=[x]
        for c in s.convs: x=F.elu(c(x,e));all_e.append(x)
        x=torch.stack(all_e,1).mean(1)
        ue,ie=x[:s.n_users],x[s.n_users:]
        u,pe,ne_=ue[ui],ie[pi],ie[ni]
        bpr=-torch.log(torch.sigmoid((u*pe).sum(-1).unsqueeze(1)-(u.unsqueeze(1)*ne_).sum(-1))+1e-10).mean()
        return {'loss':bpr+1e-5*(u.norm(2).pow(2))/ui.size(0),'bpr':bpr}

    def predict(s,e,itf,ui):
        s.eval()
        with torch.no_grad():
            ii=s.ie.weight+s.ienc(itf)
            x=torch.cat([s.ue.weight,ii],0)
            for c in s.convs:x=F.elu(c(x,e))
            return torch.mm(x[:s.n_users][ui],x[s.n_users:].t())

