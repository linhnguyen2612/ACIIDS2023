def evaluate(model, mname, edge, data, uid, cold, dev, uf=None, itf=None, ks=[10, 20, 50]):
    if not data:
        return {}
    model.eval()
    users, items = [d[0] for d in data], [d[1] for d in data]
    bs, metrics = 256, {f'{m}@{k}': [] for k in ks for m in ['R', 'HR', 'NDCG']}
    for st in range(0, len(users), bs):
        en = min(st + bs, len(users))
        bu, bi = users[st:en], items[st:en]
        ui, gt = torch.LongTensor(bu).to(dev), torch.LongTensor(bi).to(dev)
        ic = torch.BoolTensor([u in cold for u in bu]).to(dev)
        with torch.no_grad():
            if mname == 'GIFT4Rec':
                sc = model.predict(edge, uf, ui, ic if ic.any() else None)
            elif mname == 'MeLU':
                sc = model.predict(ui, uf, itf)
            elif mname == 'KGAT':
                sc = model.predict(edge, itf, ui)
            elif mname == 'KGAT_DropoutNet':
                sc = model.predict(edge, uf, itf, ui)
            else:
                sc = model.predict(edge, ui)
        for i, u in enumerate(bu):
            if u in uid:
                sc[i, uid[u]] = float('-inf')
        _, tk = torch.topk(sc, max(ks), 1)
        for k in ks:
            for i, (t, g) in enumerate(zip(tk[:, :k], gt)):
                h = (t == g).any().float().item()
                metrics[f'R@{k}'].append(h)
                metrics[f'HR@{k}'].append(h)
                if h:
                    metrics[f'NDCG@{k}'].append(1.0 / np.log2((t == g).nonzero(as_tuple=True)[0][0].item() + 2))
                else:
                    metrics[f'NDCG@{k}'].append(0.0)
    return {k: np.mean(v) * 100 for k, v in metrics.items()}

def train_model(model, mname, splits, edge, uid, cold, cfg, dev, uf=None, itf=None):
    model = model.to(dev)
    ds = TrainDataset(splits['train'], model.n_items, uid, cfg['neg_samples'])
    ld = DataLoader(ds, cfg['batch_size'], shuffle=True, collate_fn=collate_fn, num_workers=0)
    opt = torch.optim.AdamW(model.parameters(), lr=cfg['lr'], weight_decay=cfg['weight_decay'])
    sch = torch.optim.lr_scheduler.StepLR(opt, 20, 0.95)
    best_s, best_st = 0, None
    if mname == 'GIFT4Rec':
        nci = torch.LongTensor([u for u in range(model.n_users) if u not in cold]).to(dev)
    print(f"\n{'='*60}\n🚀 Training {mname}\n{'='*60}")
    for ep in range(1, cfg['epochs'] + 1):
        model.train()
        tl = 0
        for us, ps, ns in tqdm(ld, desc=f"Epoch {ep}", leave=False):
            us, ps, ns = us.to(dev), ps.to(dev), ns.to(dev)
            opt.zero_grad()
            if mname == 'GIFT4Rec':
                out = model(edge, uf, us, ps, ns)
            elif mname == 'MeLU':
                out = model(us, ps, ns, uf, itf)
            elif mname == 'KGAT':
                out = model(edge, itf, us, ps, ns)
            elif mname == 'KGAT_DropoutNet':
                out = model(edge, uf, itf, us, ps, ns)
            else:
                out = model(edge, us, ps, ns)
            out['loss'].backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            opt.step()
            tl += out['loss'].item()
        if mname == 'LightGCL' and ep == 1:
            model.compute_svd(edge)
        sch.step()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
        if ep % cfg['eval_freq'] == 0 or ep == 1:
            if mname == 'GIFT4Rec':
                model.update_mean(edge, nci)
            res = {}
            for n, d in [('active', splits['test_active']), ('warm', splits['test_warm']), ('cold', splits['test_cold'])]:
                if d:
                    res[n] = evaluate(model, mname, edge, d, uid, cold, dev, uf, itf, cfg['k_list'])
            if res:
                ov = {m: np.mean([res[s][m] for s in res if m in res.get(s, {})]) for m in ['R@10', 'R@20', 'R@50', 'HR@10', 'HR@20', 'HR@50', 'NDCG@10', 'NDCG@20', 'NDCG@50']}
                res['overall'] = ov
                if ov.get('NDCG@20', 0) > best_s:
                    best_s = ov['NDCG@20']
                    best_st = copy.deepcopy(model.state_dict())
                print(f"Ep{ep}: Loss={tl/len(ld):.4f} | Active R@20={res.get('active',{}).get('R@20',0):.2f} Cold R@20={res.get('cold',{}).get('R@20',0):.2f}")
    if best_st:
        model.load_state_dict(best_st)
    return model

def final_eval(model, mname, edge, splits, uid, cold, dev, uf=None, itf=None):
    if mname == 'GIFT4Rec':
        nci = torch.LongTensor([u for u in range(model.n_users) if u not in cold]).to(dev)
        model.update_mean(edge, nci)
    res = {}
    for n, d in [('active', splits['test_active']), ('warm', splits['test_warm']), ('cold', splits['test_cold'])]:
        if d:
            res[n] = evaluate(model, mname, edge, d, uid, cold, dev, uf, itf, CONFIG['k_list'])
    if res:
        ov = {m: np.mean([res[s][m] for s in res if m in res.get(s, {})]) for m in ['R@10', 'R@20', 'R@50', 'HR@10', 'HR@20', 'HR@50', 'NDCG@10', 'NDCG@20', 'NDCG@50']}
        res['overall'] = ov
    return res

