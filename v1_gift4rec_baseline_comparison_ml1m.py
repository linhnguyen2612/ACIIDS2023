class SGL(nn.Module):
    def __init__(s,nu,ni,ed=64,nl=2,ct=0.2,cw=0.1,ar=0.1):
        super().__init__()
        s.n_users,s.n_items,s.ct,s.cw,s.ar=nu,ni,ct,cw,ar
        s.gnn=BaseGNN(nu,ni,ed,nl)

    def aug(s,e): return e[:,torch.rand(e.size(1),device=e.device)>s.ar]

    def nce(s,z1,z2):
        z1,z2=F.normalize(z1,-1),F.normalize(z2,-1)
        return (-((z1*z2).sum(-1)/s.ct)+torch.logsumexp(torch.mm(z1,z2.t())/s.ct,1)).mean()

    def forward(s,e,ui,pi,ni):
        ue,ie=s.gnn(e);u,pe,ne=ue[ui],ie[pi],ie[ni]
        bpr=-torch.log(torch.sigmoid((u*pe).sum(-1).unsqueeze(1)-(u.unsqueeze(1)*ne).sum(-1))+1e-10).mean()
        u1,i1=s.gnn(s.aug(e));u2,i2=s.gnn(s.aug(e))
        cl=(s.nce(u1[ui],u2[ui])+s.nce(i1[pi],i2[pi]))/2
        return {'loss':bpr+s.cw*cl+1e-5*(u.norm(2).pow(2))/ui.size(0),'bpr':bpr,'cl':cl}

    def predict(s,e,ui):
        s.eval()
        with torch.no_grad(): ue,ie=s.gnn(e);return torch.mm(ue[ui],ie.t())

