class KGATDropoutNet(nn.Module):
    def __init__(s,nu,ni,ufd,ifd,ed=64,nl=2,nh=4,dr=0.1,dnr=0.5):
        super().__init__()
        s.n_users,s.n_items,s.dnr=nu,ni,dnr
        s.ue,s.ie=nn.Embedding(nu,ed),nn.Embedding(ni,ed)
        s.ucont=nn.Sequential(nn.Linear(ufd,ed*2),nn.ReLU(),nn.Dropout(0.2),nn.Linear(ed*2,ed))
        s.icont=nn.Sequential(nn.Linear(ifd,ed*2),nn.ReLU(),nn.Dropout(0.2),nn.Linear(ed*2,ed))
        s.convs=nn.ModuleList([KGATConv(ed,ed,nh,dr) for _ in range(nl)])
        s.fuse=nn.Sequential(nn.Linear(ed*2,ed),nn.ReLU())
        nn.init.xavier_uniform_(s.ue.weight);nn.init.xavier_uniform_(s.ie.weight)

    def dn_aug(s,cf,cont):
        if s.training:
            m=torch.rand(cf.size(0),1,device=cf.device)<s.dnr
            return torch.where(m,cont,s.fuse(torch.cat([cf,cont],-1)))
        return s.fuse(torch.cat([cf,cont],-1))

    def get_emb(s,e,uf,itf):
        uc,ic=s.ucont(uf),s.icont(itf)
        ii=s.ie.weight+ic
        x=torch.cat([s.ue.weight,ii],0)
        all_e=[x]
        for c in s.convs:x=F.elu(c(x,e));all_e.append(x)
        x=torch.stack(all_e,1).mean(1)
        ucf,icf=x[:s.n_users],x[s.n_users:]
        return s.dn_aug(ucf,uc),s.dn_aug(icf,ic)

    def forward(s,e,uf,itf,ui,pi,ni):
        ue,ie=s.get_emb(e,uf,itf)
        u,pe,ne_=ue[ui],ie[pi],ie[ni]
        bpr=-torch.log(torch.sigmoid((u*pe).sum(-1).unsqueeze(1)-(u.unsqueeze(1)*ne_).sum(-1))+1e-10).mean()
        return {'loss':bpr+1e-5*(u.norm(2).pow(2))/ui.size(0),'bpr':bpr}

    def predict(s,e,uf,itf,ui):
        s.eval()
        with torch.no_grad():
            ue,ie=s.get_emb(e,uf,itf)
            return torch.mm(ue[ui],ie.t())

