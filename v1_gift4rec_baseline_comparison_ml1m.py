class MeLU(nn.Module):
    def __init__(s,nu,ni,ufd,ifd,ed=64,hd=128):
        super().__init__()
        s.n_users,s.n_items=nu,ni
        s.ue,s.ie=nn.Embedding(nu,ed),nn.Embedding(ni,ed)
        s.uenc=nn.Sequential(nn.Linear(ufd,hd),nn.ReLU(),nn.Linear(hd,ed))
        s.ienc=nn.Sequential(nn.Linear(ifd,hd),nn.ReLU(),nn.Linear(hd,ed))
        s.meta=nn.Sequential(nn.Linear(ed*4,hd),nn.ReLU(),nn.Dropout(0.2),nn.Linear(hd,ed),nn.ReLU())
        s.pred=nn.Linear(ed,1)
        nn.init.xavier_uniform_(s.ue.weight);nn.init.xavier_uniform_(s.ie.weight)

    def forward(s,ui,pi,ni,uf,itf):
        uc=torch.cat([s.ue(ui),s.uenc(uf[ui])],-1)
        pc=torch.cat([s.ie(pi),s.ienc(itf[pi])],-1)
        nc=torch.cat([s.ie(ni),s.ienc(itf[ni])],-1)
        ps=s.pred(s.meta(torch.cat([uc,pc],-1))).squeeze(-1)
        ue=uc.unsqueeze(1).expand(-1,ni.size(1),-1)
        ns=s.pred(s.meta(torch.cat([ue,nc],-1))).squeeze(-1)
        bpr=-torch.log(torch.sigmoid(ps.unsqueeze(1)-ns)+1e-10).mean()
        return {'loss':bpr+1e-5*s.ue(ui).norm(2).pow(2)/ui.size(0),'bpr':bpr}

    def predict(s,ui,uf,itf):
        s.eval()
        with torch.no_grad():
            uc=torch.cat([s.ue(ui),s.uenc(uf[ui])],-1)
            ic=torch.cat([s.ie.weight,s.ienc(itf)],-1)
            scores=[]
            for i in range(ui.size(0)):
                ue=uc[i:i+1].expand(s.n_items,-1)
                scores.append(s.pred(s.meta(torch.cat([ue,ic],-1))).squeeze(-1))
            return torch.stack(scores,0)

