class GIFT4Rec(nn.Module):
    def __init__(s,nu,ni,ufd,ed=64,nl=2,hd=128,dr=0.2):
        super().__init__()
        s.n_users,s.n_items,s.embed_dim,s.dr=nu,ni,ed,dr
        s.gnn=BaseGNN(nu,ni,ed,nl)
        s.side_enc=nn.Sequential(nn.Linear(ufd,ed*2),nn.LayerNorm(ed*2),nn.ReLU(),nn.Dropout(0.2),nn.Linear(ed*2,ed),nn.LayerNorm(ed))
        s.wg=nn.Sequential(nn.Linear(ed*2,hd),nn.LayerNorm(hd),nn.ReLU(),nn.Dropout(0.2),nn.Linear(hd,hd//2),nn.ReLU(),nn.Linear(hd//2,1),nn.Sigmoid())
        s.register_buffer('mean_emb',torch.zeros(ed))

    def update_mean(s,e,ids):
        with torch.no_grad():
            u,_=s.gnn(e)
            s.mean_emb=u[ids].mean(0)

    def fuse(s,b,si,do=True):
        a=s.wg(torch.cat([b,si],-1))
        if do and s.training:
            m=torch.rand(a.size(0),1,device=a.device)<s.dr
            return torch.where(m.expand_as(b),si,a*b+(1-a)*si),a
        return a*b+(1-a)*si,a

    def forward(s,e,uf,ui,pi,ni):
        ue,ie=s.gnn(e)
        se=s.side_enc(uf)
        ub,us,pe,ne=ue[ui],se[ui],ie[pi],ie[ni]
        fu,a=s.fuse(ub,us)
        ps,ns=(fu*pe).sum(-1),(fu.unsqueeze(1)*ne).sum(-1)
        bpr=-torch.log(torch.sigmoid(ps.unsqueeze(1)-ns)+1e-10).mean()
        l2=1e-5*(ub.norm(2).pow(2)+pe.norm(2).pow(2)+ne.norm(2).pow(2))/ui.size(0)
        return {'loss':bpr+l2,'bpr':bpr,'alpha':a.mean()}

    def predict(s,e,uf,ui,ic=None):
        s.eval()
        with torch.no_grad():
            ue,ie=s.gnn(e)
            se=s.side_enc(uf)
            ub,us=ue[ui],se[ui]
            if ic is not None and ic.any(): ub[ic]=s.mean_emb.expand(ic.sum(),-1)
            fu,_=s.fuse(ub,us,False)
            return torch.mm(fu,ie.t())

