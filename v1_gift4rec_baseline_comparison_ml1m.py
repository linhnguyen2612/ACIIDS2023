class NCL(nn.Module):
    def __init__(s,nu,ni,ed=64,nl=2,ct=0.2,cw=0.1,nc=100):
        super().__init__()
        s.n_users,s.n_items,s.ct,s.cw=nu,ni,ct,cw
        s.gnn=BaseGNN(nu,ni,ed,nl)
        s.uc=nn.Parameter(torch.randn(nc,ed)*0.1)
        s.ic=nn.Parameter(torch.randn(nc,ed)*0.1)

    def pcl(s,emb,cent,idx):
        e,c=F.normalize(emb[idx],-1),F.normalize(cent,-1)
        ass=F.softmax(torch.mm(F.normalize(emb,-1),c.t())/s.ct,-1)
        proto=F.normalize(torch.mm(ass[idx],c),-1)
        return (-((e*proto).sum(-1)/s.ct)+torch.logsumexp(torch.mm(e,c.t())/s.ct,1)).mean()

    def forward(s,e,ui,pi,ni):
        ue,ie=s.gnn(e);u,pe,ne_=ue[ui],ie[pi],ie[ni]
        bpr=-torch.log(torch.sigmoid((u*pe).sum(-1).unsqueeze(1)-(u.unsqueeze(1)*ne_).sum(-1))+1e-10).mean()
        cl=(s.pcl(ue,s.uc,ui)+s.pcl(ie,s.ic,pi))/2
        return {'loss':bpr+s.cw*cl+1e-5*(u.norm(2).pow(2))/ui.size(0),'bpr':bpr,'cl':cl}

    def predict(s,e,ui):
        s.eval()
        with torch.no_grad(): ue,ie=s.gnn(e);return torch.mm(ue[ui],ie.t())

