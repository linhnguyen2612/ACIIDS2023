def split_users(ratings, ar=0.8, cr=0.1):
    counts = ratings.groupby('uidx').size().sort_values(ascending=False)
    n = len(counts)
    return set(counts.iloc[:int(n*ar)].index), set(counts.index) - set(counts.iloc[:int(n*ar)].index) - set(counts.iloc[-int(n*cr):].index), set(counts.iloc[-int(n*cr):].index)

def create_splits(ratings, active, warm, cold):
    train, val, ta, tw, tc = [], [], [], [], []
    for uid, g in ratings.groupby('uidx'):
        items = g['iidx'].tolist()
        if uid in active:
            if len(items)>=3:
                train.extend([(uid,i) for i in items[:-2]])
                val.append((uid,items[-2]))
                ta.append((uid,items[-1]))
            elif len(items)==2:
                train.append((uid,items[0]))
                ta.append((uid,items[1]))
            else:
                train.append((uid,items[0]))
        elif uid in warm:
            if len(items)>=2:
                train.extend([(uid,i) for i in items[:-1]])
                tw.append((uid,items[-1]))
            else:
                train.append((uid,items[0]))
        else:
            if items:
                tc.append((uid,items[0]))
    return {'train':train,'val':val,'test_active':ta,'test_warm':tw,'test_cold':tc}

