class LightGCL(nn.Module):
    def __init__(s,nu,ni,ed=64,nl=2,ct=0.2,cw=0.1,sq=5):
        super().__init__()
        s.n_users,s.n_items,s.ct,s.cw,s.sq=nu,ni,ct,cw,sq
        s.gnn=BaseGNN(nu,ni,ed,nl)
        s.svd_u=s.svd_v=None

    def compute_svd(s,e):
        from scipy.sparse.linalg import svds
        n=s.n_users+s.n_items;r,c=e.cpu().numpy()
        adj=csr_matrix((np.ones(len(r)),(r,c)),shape=(n,n))
        try:
            u,sv,vt=svds(adj.astype(np.float32),k=min(s.sq,min(adj.shape)-1))
            s.svd_u=torch.FloatTensor(u@np.diag(np.sqrt(sv))).to(e.device)
            s.svd_v=torch.FloatTensor(vt.T@np.diag(np.sqrt(sv))).to(e.device)
        except:pass

    def nce(s,z1,z2):
        z1,z2=F.normalize(z1,-1),F.normalize(z2,-1)
        return (-((z1*z2).sum(-1)/s.ct)+torch.logsumexp(torch.mm(z1,z2.t())/s.ct,1)).mean()

    def forward(s,e,ui,pi,ni):
        ue,ie=s.gnn(e);u,pe,ne_=ue[ui],ie[pi],ie[ni]
        bpr=-torch.log(torch.sigmoid((u*pe).sum(-1).unsqueeze(1)-(u.unsqueeze(1)*ne_).sum(-1))+1e-10).mean()
        cl=torch.tensor(0.0,device=e.device)
        if s.svd_u is not None:
            try:cl=(s.nce(ue[ui],s.svd_u[:s.n_users][ui])+s.nce(ie[pi],s.svd_v[s.n_users:][pi]))/2
            except:pass
        return {'loss':bpr+s.cw*cl+1e-5*(u.norm(2).pow(2))/ui.size(0),'bpr':bpr,'cl':cl}

    def predict(s,e,ui):
        s.eval()
        with torch.no_grad(): ue,ie=s.gnn(e);return torch.mm(ue[ui],ie.t())

