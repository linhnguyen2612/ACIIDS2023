def prepare_data(ratings, users, movies):
    all_users, all_items = sorted(ratings['user_id'].unique()), sorted(ratings['item_id'].unique())
    u2i, i2i = {u: i for i, u in enumerate(all_users)}, {i: idx for idx, i in enumerate(all_items)}
    ratings = ratings.copy()
    ratings['uidx'], ratings['iidx'] = ratings['user_id'].map(u2i), ratings['item_id'].map(i2i)
    n_users, n_items = len(all_users), len(all_items)

    # User features
    users_f = users[users['user_id'].isin(all_users)].copy().set_index('user_id').loc[all_users].reset_index()
    users_f['g'], users_f['a'], users_f['o'] = users_f['gender'].map({'M':0,'F':1}), LabelEncoder().fit_transform(users_f['age']), LabelEncoder().fit_transform(users_f['occupation'])
    ng, na, no = 2, users_f['a'].nunique(), users_f['o'].nunique()
    user_feats = np.zeros((n_users, ng+na+no), dtype=np.float32)
    for i, (_, r) in enumerate(users_f.iterrows()):
        user_feats[i, r['g']], user_feats[i, ng+r['a']], user_feats[i, ng+na+r['o']] = 1, 1, 1

    # Item features
    all_genres = sorted(set(g for gs in movies['genres'] for g in gs.split('|')))
    genre2idx = {g: i for i, g in enumerate(all_genres)}
    movies_f = movies[movies['item_id'].isin(all_items)].copy()
    movies_f['iidx'] = movies_f['item_id'].map(i2i)
    item_feats = np.zeros((n_items, len(all_genres)), dtype=np.float32)
    for _, row in movies_f.iterrows():
        for g in row['genres'].split('|'): item_feats[row['iidx'], genre2idx[g]] = 1

    return ratings, n_users, n_items, torch.FloatTensor(user_feats), torch.FloatTensor(item_feats)

