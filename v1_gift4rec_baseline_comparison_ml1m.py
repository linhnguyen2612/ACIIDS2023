class LightGCNConv(nn.Module):
    def forward(self, x, e):
        r,c = e
        d = torch.bincount(r,minlength=x.size(0)).float().pow(-0.5)
        d[d==float('inf')]=0
        out = torch.zeros_like(x)
        out.index_add_(0,r,x[c]*(d[r]*d[c]).unsqueeze(-1))
        return out

class BaseGNN(nn.Module):
    def __init__(self,nu,ni,ed=64,nl=2):
        super().__init__()
        self.n_users,self.n_items=nu,ni
        self.user_emb,self.item_emb=nn.Embedding(nu,ed),nn.Embedding(ni,ed)
        self.convs=nn.ModuleList([LightGCNConv() for _ in range(nl)])
        nn.init.xavier_uniform_(self.user_emb.weight);nn.init.xavier_uniform_(self.item_emb.weight)

    def forward(self,e):
        x=torch.cat([self.user_emb.weight,self.item_emb.weight],0)
        all_e=[x]
        for c in self.convs: x=c(x,e);all_e.append(x)
        x=torch.stack(all_e,1).mean(1)
        return x[:self.n_users],x[self.n_users:]

def build_graph(data,nu,ni,dev):
    e=[]
    for u,i in data: e.append([u,nu+i]);e.append([nu+i,u])
    return torch.LongTensor(e).t().contiguous().to(dev)

